-- Supabase (Postgres) schema for the trading bot.
-- Run once in the Supabase SQL Editor (project ibmhrlcocptfjlwmrkdo),
-- or locally / in CI with:  python -m db.init_db
-- Safe to re-run: tables/seed are only created if missing.

create table if not exists account (
    id       integer primary key,
    cash_usd numeric not null default 258,
    cash_inr numeric not null default 0
);

create table if not exists portfolio (
    id          bigint generated by default as identity primary key,
    ticker      text not null unique,
    shares      numeric not null,
    buy_price   numeric not null,
    buy_date    date not null default current_date,
    currency    text not null default 'USD',
    local_value numeric,
    usd_value   numeric,
    risk_level  text,
    stop_loss   numeric
);

create table if not exists trades (
    id               bigint generated by default as identity primary key,
    date             timestamptz not null default now(),
    action           text not null,
    ticker           text not null,
    price            numeric not null,
    shares           numeric not null,
    currency         text not null default 'USD',
    realized_pnl     numeric not null default 0,
    pnl_pct          numeric not null default 0,
    entry_price      numeric,
    entry_date       date,
    remaining_shares numeric
);

create table if not exists performance (
    id          bigint generated by default as identity primary key,
    date        date not null default current_date,
    total_value numeric not null
);

-- Initial capital: $258, US-only. Never overwrite an existing balance.
insert into account (id, cash_usd, cash_inr)
values (1, 258, 0)
on conflict (id) do nothing;
